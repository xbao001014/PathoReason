"""Generate structural TypeScript models from the API's Pydantic/OpenAPI schema."""
import json
from pathlib import Path
from pathoreason.api import app
root=Path(__file__).resolve().parents[1]
schema=app.openapi()
def ts(node):
    if '$ref' in node:return node['$ref'].split('/')[-1]
    if 'const' in node:return json.dumps(node['const'])
    if 'enum' in node:return ' | '.join(json.dumps(x) for x in node['enum'])
    for key,sep in [('anyOf',' | '),('oneOf',' | '),('allOf',' & ')]:
        if key in node:return '('+sep.join(ts(x) for x in node[key])+')'
    kind=node.get('type')
    if kind=='array':return '('+ts(node.get('items',{}))+')[]'
    if kind=='object' or 'properties' in node:
        properties=node.get('properties',{});required=node.get('required',[])
        fields=[json.dumps(k)+('' if k in required else '?')+': '+ts(v)+';' for k,v in properties.items()]
        if node.get('additionalProperties'):
            fields.append('[key: string]: '+(ts(node['additionalProperties']) if isinstance(node['additionalProperties'],dict) else 'unknown')+';')
        return '{ '+' '.join(fields)+' }'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')
text='// Generated by scripts/export_web_types.py; edit Python contracts, not this file.\n'
for name,value in schema['components']['schemas'].items():text+='export type '+name+' = '+ts(value)+';\n'
(root/'apps/web/src/generated.ts').write_text(text)
(root/'contracts/api-p5-data-browser.openapi.json').write_text(json.dumps(schema,indent=2)+'\n')
print('Generated API types')
